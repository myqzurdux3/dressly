/// Language codes this app ships strings for. Must match
/// `LocaleController.supportedLocales`.
List<String> get supportedLanguageCodes => _strings.keys.toList();

/// Every key defined for [code]. Exposed for the locale-parity test.
Set<String> translationKeys(String code) =>
    (_strings[code] ?? const {}).keys.toSet();

/// The raw string for [code] + [key], or null. Exposed for the parity test.
String? rawTranslation(String code, String key) => _strings[code]?[key];

/// Substitute `{name}` placeholders. Unknown placeholders are left as-is so a
/// mistake is visible in the UI rather than silently dropping text.
String _fill(String template, Map<String, Object?>? params) {
  if (params == null || params.isEmpty) return template;
  var out = template;
  params.forEach((name, value) {
    out = out.replaceAll('{$name}', '$value');
  });
  return out;
}

/// Placeholder names referenced by a template, e.g. `{count}` -> `count`.
Set<String> placeholdersOf(String template) => RegExp(r'\{(\w+)\}')
    .allMatches(template)
    .map((m) => m.group(1)!)
    .toSet();

String _lookup(String code, String key) =>
    _strings[code]?[key] ?? _strings['en']?[key] ?? key;

/// Translate [key], optionally substituting `{placeholder}` values.
String tr(BuildContext context, String key, [Map<String, Object?>? params]) {
  final code = Localizations.localeOf(context).languageCode;
  return _fill(_lookup(code, key), params);
}

/// Like [tr] but returns [fallback] when the key has no translation (e.g. a
/// server-provided algorithm id we haven't localised yet).
String trOr(BuildContext context, String key, String fallback,
    [Map<String, Object?>? params]) {
  final code = Localizations.localeOf(context).languageCode;
  final v = _lookup(code, key);
  return v == key ? _fill(fallback, params) : _fill(v, params);
}

/// Count-aware translation.
///
/// Looks up `<baseKey>.one` or `<baseKey>.other` and makes `{count}` available
/// as a placeholder. This replaces the `n == 1 ? tr('x.item') : tr('x.items')`
/// pattern that was repeated across the screens — which silently produced the
/// wrong form in French for 0 ("0 article", not "0 articles").
String trPlural(BuildContext context, String baseKey, int count,
    [Map<String, Object?>? params]) {
  final code = Localizations.localeOf(context).languageCode;
  final form = _pluralForm(code, count);
  var template = _strings[code]?['$baseKey.$form'] ??
      _strings[code]?['$baseKey.other'] ??
      _strings['en']?['$baseKey.$form'] ??
      _strings['en']?['$baseKey.other'];
  template ??= baseKey;
  return _fill(template, {'count': count, ...?params});
}

/// Which plural form a language uses for [count].
///
/// English: 1 is singular, everything else (including 0) is plural.
/// French: 0 and 1 are both singular. Add a case here per new language rather
/// than assuming the English rule.
String _pluralForm(String code, int count) {
  switch (code) {
    case 'fr':
      return (count == 0 || count == 1) ? 'one' : 'other';
    default:
      return count == 1 ? 'one' : 'other';
  }
}
