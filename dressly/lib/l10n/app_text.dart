/// so a missing translation degrades gracefully instead of crashing.
///
/// Add new UI strings here as they're localized — English is the source of
/// truth; other languages only need the keys they translate.
///
/// ## Why not ARB / gen_l10n?
///
/// The generated `AppLocalizations` exposes one Dart getter per message and has
/// no runtime `lookup(String)` API. This app needs exactly that: keys are built
/// from data at runtime (`cat.<category>`, `color.<name>`, `cut.<cut>`) and,
/// crucially, from ids the *server* supplies — `trOr(context, 'algoName.' + a.id,
/// a.label)` translates the algorithms we know and falls back to the server's
/// own label for any new one. Under codegen a new server-side algorithm would
/// have no accessor at all, so that graceful path would be gone.
///
/// What ARB really buys — placeholder handling, plurals, and catching a key
/// that exists in one locale but not another — is provided here instead by
/// [tr]'s `params`, by [trPlural], and by `test/l10n_test.dart`, which fails if
/// the locales drift apart.
